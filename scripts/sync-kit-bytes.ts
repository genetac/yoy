/* Measures authored kit-content bytes and generates catalog/kit-bytes.ts.
   Run after any kit-content change: bun scripts/sync-kit-bytes.ts */
import { writeFileSync } from "node:fs";

const KIT_IDS = [
  "B-TP-1", "B-TP-2", "B-TP-3", "B-TP-4",
  "B-TK-1", "B-TK-2", "B-TK-3", "B-TK-4",
  "B-NS-1", "B-NS-2", "B-NS-3", "B-NS-4",
  "B-AS-1", "B-AS-2", "B-AS-3", "B-AS-4",
  "C-WK-1", "C-WK-2", "C-WK-3", "C-WK-4",
];

const bytes = (s: string) => new TextEncoder().encode(s).length;

const out: Record<string, Record<string, number>> = {};

// Shared root files, replicated per kit (root paths differ from source keys)
const shared = await import("../src/components/omniforge/kit-content/_shared/content.ts");
const sharedBytes: Record<string, number> = {};
for (const [k, v] of Object.entries(shared.files)) sharedBytes[k] = bytes(v);
out._shared = sharedBytes;

let totalFiles = 0;
for (const id of KIT_IDS) {
  const mod = await import(`../src/components/omniforge/kit-content/${id}/content.ts`);
  const rec: Record<string, number> = {};
  for (const [k, v] of Object.entries(mod.files as Record<string, string>)) {
    rec[k] = bytes(v);
    totalFiles++;
  }
  // Root entries (paths as they appear in the bundle)
  rec["README.md"] = sharedBytes["root/README.md"];
  rec["LICENSE.md"] = sharedBytes["root/LICENSE.md"];
  rec["CHANGELOG.md"] = sharedBytes["root/CHANGELOG.md"];
  rec["QUICK-START.md"] = sharedBytes["root/QUICK-START.md"];
  rec["duplicate-link.md"] = sharedBytes["root/duplicate-link.md"];
  out[id] = rec;
}

const body =
`/* ════════════════════════════════════════════════════════════════════
   Measured byte sizes for authored kit files — GENERATED FILE.
   Regenerated by \`bun scripts/sync-kit-bytes.ts\` after kit-content
   changes. Keys: offerId → bundle path → UTF-8 bytes of the authored
   source. Generated twins (.docx/.pdf) estimate from their .md source.
   ════════════════════════════════════════════════════════════════════ */

export const KIT_BYTES: Record<string, Record<string, number>> = ${JSON.stringify(out, null, 1)};
`;

writeFileSync("/home/z/my-project/src/components/omniforge/catalog/kit-bytes.ts", body);
console.log(`kit-bytes.ts generated — ${KIT_IDS.length} kits, ${totalFiles} content files measured`);
